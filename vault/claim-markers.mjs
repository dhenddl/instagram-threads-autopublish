// claim-markers.mjs — 볼트 미검증 마커 규약의 **단일 출처**. 2026-08-24 신설.
//
// 규약은 두 자리가 있고 **자리가 뜻을 바꾼다.**
//
//   ① 문장 끝·중간, 공백 뒤        `… 분리가 안 된다 [미검증]`   → **주장(해석)이 미검증**
//   ② 숫자 바로 뒤, 공백 없이      `-72%[미검증]`                → **그 숫자가 미검증**
//
// ★ ②는 새로 만든 게 아니라 **이미 자생한 표기를 공식화한 것**이다 —
//   2026-07-31 브리핑에 `워터마크 잔존 -N%[미검증]` 이 이미 있었다.
//
// 왜 갈라야 했나 (2026-08-24):
//   「쓰면 안 되는 숫자」 대장을 만들면서 원고 숫자를 자동 대조하려 했더니 오탐이 압도적이었다.
//   근본 원인은 정확도가 아니라 **추론**이었다 — 마커가 주장에 붙어 있으니
//   "마커 근처의 숫자 = 미검증 숫자"가 성립하지 않는다.
//   「<성과 기록 문서>」의 *"도달이 <실측 도달값>이라 … 분리가 안 된다 [미검증]"* 에서 미검증인 것은
//   **<실측 도달값>가 아니라 그 해석**이고, <실측 도달값>는 API 실측값이라 **써도 된다.**
//   → ②를 도입하면 **숫자 단위 게이트가 성립한다.** 사람이 한 번 판단해 표기를 옮기면
//     그 뒤로는 기계가 지킬 수 있다.
//
// ⚠️ ①을 ②로 일괄 치환하면 안 된다. 사례마다 사람이 판단한다.

export const MARKERS = [
  '미검증', '미측정', '미확인', '확인 필요', '미확정',   // ⛔ 인용 금지
  '추정', '산출', '해석', '조건부', '가설',              // ⚠️ 「우리 해석」임을 밝히면 사용 가능
];

/** ⛔ 인용하면 안 되는 등급 (게이트가 막는 것) */
export const BLOCKING = new Set(['미검증', '미측정', '미확인', '확인 필요', '미확정']);

const M = MARKERS.join('|');

// 숫자 토큰 — 범위(30~40%)·부호(-72%)·단위(5억)·소수(4.84)를 한 덩어리로 잡는다.
const UNIT = '%|만|억|원|배|명|건|편|일|개|장|회|시간|분|초|달|주|년|자|KB|MB|GB';
// ⚠️⚠️ 공백은 **단위가 따라올 때만** 허용한다. `\s?(?:단위)?` 로 두면 둘 다 옵션이라
//    **단위 없이 공백만** 먹어서 `07-25 [미검증]`(①형)이 ②형으로 잡힌다
//    — 2026-08-24 실측으로 잡은 버그이고, 이건 규약의 핵심 구분을 무너뜨린다.
// ⚠️ 앞에 숫자가 오면 매칭하지 않는다 — 날짜 `2026-07-25` 에서 `-25` 를 숫자로 오독한다.
const NUM = String.raw`(?<![\d.])-?\d[\d,]*(?:\.\d+)?(?:\s?~\s?-?\d[\d,]*(?:\.\d+)?)?(?:\s?(?:${UNIT}))?`;

/** ② 숫자 바로 뒤 — 공백이 없어야 한다. 이게 「이 숫자가 미검증」이다. */
export const MARKED_NUMBER = new RegExp(`(${NUM})\\[(${M})\\]`, 'g');

/** ① 공백 뒤 또는 줄 시작 — 「주장이 미검증」. 숫자 단위 판정에 쓰면 안 된다. */
export const CLAIM_MARKER = new RegExp(`(?:^|[\\s(*_>·,.])\\[(${M})\\]`, 'g');

/** 마커 전체(위치 무관) — 대장 수집용 */
export const ANY_MARKER = new RegExp(`\\[(${M})\\]`, 'g');

/**
 * 숫자를 비교 가능한 형태로 만든다. 쉼표·공백을 걷고 **모든 부호**를 버린다.
 * 부호를 버리는 이유: 볼트는 `-72%`로 적고 원고는 `72% 떨어졌다`로 쓴다.
 * ⚠️ 앞쪽 부호만 걷으면 범위가 깨진다 — `-42~-72%` → `42~-72%` 가 되어
 *    원고의 `42~72%` 와 안 맞는다(2026-08-24 게이트 테스트에서 잡은 버그).
 *    유니코드 마이너스(−, U+2212)도 같이 걷는다 — 볼트 본문에 섞여 있다.
 */
export function normNumber(s) {
  return s.replace(/[,\s]/g, '').replace(/[-−]/g, '');
}

/**
 * 게이트를 걸 만큼 변별력이 있는 숫자인가.
 * ⚠️ 이 판정이 게이트의 정직성을 결정한다 — `10개`·`100` 같은 값에 게이트를 걸면
 *    오탐이 나고, 「신호를 믿으면 안 되는 자리」 처방 4단계 ⑤에 따라 검사 전체가 무시된다.
 * 통과 조건 — 셋 중 하나:
 *   (a) 유효숫자 3자리 이상            1,759,000 · 492 · 178
 *   (b) 소수점 포함                    4.84 · 65.5
 *   (c) 범위 표기                      30~40 · 50~500
 */
export function isDistinctive(raw) {
  const n = normNumber(raw);
  if (/~/.test(raw)) return true;
  if (/\./.test(n)) return true;
  const digits = (n.match(/\d/g) || []).length;
  return digits >= 3;
}
